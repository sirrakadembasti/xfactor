import os from 'os';
import { WindowsSandboxAdapter } from './adapters/windowsSandbox.js';
import { PortableSandboxAdapter } from './adapters/portableSandbox.js';

export class SandboxInitializationError extends Error {
    constructor(message = 'No secure OS sandbox adapter is available.') {
        super(message);
        this.name = 'SandboxInitializationError';
        this.code = 'SANDBOX_UNAVAILABLE';
    }
}

const SENSITIVE_KEY_PATTERN = /(?:API_KEY|SECRET|TOKEN|PASSWORD|CREDENTIAL|PRIVATE|AUTH|LLM|GEMINI|OPENAI|ANTHROPIC|DEEPSEEK|MISTRAL|AZURE)/i;

export const EPHEMERAL_VERIFICATION_ENV_ALLOWLIST = Object.freeze({
    AUTH_SECRET: 'verification-only-ephemeral-secret-not-for-production',
    NEXTAUTH_SECRET: 'verification-only-ephemeral-secret-not-for-production',
    NEXTAUTH_URL: 'http://localhost:3000'
});

export function isAllowedEphemeralEnv(key, value) {
    if (EPHEMERAL_VERIFICATION_ENV_ALLOWLIST[key] === value) return true;
    if (key === 'AUTH_SECRET' && value === 'verification-only-secret-minimum-32-characters') return true;
    if (key === 'NEXTAUTH_SECRET' && value === 'verification-only-secret-minimum-32-characters') return true;
    if (key === 'NEXTAUTH_URL' && value === 'http://127.0.0.1:3000') return true;
    return false;
}

export function scrubEnvironmentVariables(rawEnv = {}) {
    const clean = {};
    for (const [key, value] of Object.entries(rawEnv)) {
        if (isAllowedEphemeralEnv(key, value)) {
            clean[key] = value;
            continue;
        }
        if (!SENSITIVE_KEY_PATTERN.test(key)) {
            clean[key] = value;
        }
    }
    return clean;
}

// Throwaway demo passwords generated by roleSessionAdapter for one verification run. Only the
// caller's explicit ephemeralEnv channel can supply them; the host env is still scrubbed of every
// PASSWORD-like key. Anything else in that channel fails closed.
const EPHEMERAL_DEMO_PASSWORD_KEY = /^XFACTOR_DEMO_PASSWORD_[A-Z0-9_]+$/;
const EPHEMERAL_DEMO_PASSWORD_VALUE = /^[A-Za-z0-9_-]{32}$/;
export function validateEphemeralEnv(ephemeralEnv = {}) {
    if (ephemeralEnv === null || typeof ephemeralEnv !== 'object' || Array.isArray(ephemeralEnv)) {
        throw new SandboxInitializationError('Ephemeral environment must be a plain object.');
    }
    const clean = {};
    for (const [key, value] of Object.entries(ephemeralEnv)) {
        if (!EPHEMERAL_DEMO_PASSWORD_KEY.test(key) || typeof value !== 'string' || !EPHEMERAL_DEMO_PASSWORD_VALUE.test(value)) {
            throw new SandboxInitializationError(`Ephemeral environment rejects "${key}": only run-generated demo passwords are allowed.`);
        }
        clean[key] = value;
    }
    return clean;
}

const adapters = {
    windows: new WindowsSandboxAdapter(),
    bubblewrap: new PortableSandboxAdapter('bubblewrap'),
    docker: new PortableSandboxAdapter('docker')
};

export function getActiveSandboxAdapter(requestedId = null) {
    if (requestedId && adapters[requestedId]) {
        return adapters[requestedId];
    }

    if (requestedId) {
        throw new SandboxInitializationError(`Requested sandbox adapter "${requestedId}" is not recognized.`);
    }

    const platform = os.platform();
    if (platform === 'win32') {
        return adapters.windows;
    } else if (platform === 'linux' || platform === 'darwin') {
        return adapters.bubblewrap;
    }

    throw new SandboxInitializationError(`No compatible sandbox adapter found for platform: ${platform}`);
}

const consentedLocalCapabilities = new WeakSet();
export function authorizeLocalExecutionAdapter(adapter, { trustLocalCode = false } = {}) {
    const capabilities = adapter?.getCapabilities?.();
    if (trustLocalCode !== true) throw new SandboxInitializationError('Local execution requires explicit operator consent.');
    if (!Object.isFrozen(capabilities) || capabilities?.executionProfile !== 'local-trusted' || capabilities.isolation !== false || capabilities.osIsolation !== false || capabilities.available !== true) throw new SandboxInitializationError('Invalid local execution capabilities.');
    consentedLocalCapabilities.add(capabilities);
    return adapter;
}

export function requireSandboxCapabilities(adapter) {
    if (typeof adapter?.getCapabilities !== 'function') {
        if (adapter?.id && adapter.id !== 'unknown' && typeof adapter?.isAvailable === 'function' && adapter.isAvailable()) {
            return {
                adapterId: adapter.id,
                available: true,
                isolation: true,
                networkAllowed: false
            };
        }
        throw new SandboxInitializationError(
            `Sandbox adapter "${adapter?.id || 'unknown'}" has no proven capabilities.`
        );
    }

    const capabilities = adapter.getCapabilities();
    if (!capabilities?.available || (capabilities.isolation !== true && !consentedLocalCapabilities.has(capabilities))) {
        throw new SandboxInitializationError(
            capabilities?.reason || `Sandbox adapter "${adapter.id || 'unknown'}" is unavailable.`
        );
    }
    return capabilities;
}

export async function executeInSandbox(command, args = [], options = {}) {
    const adapter = options.adapter || getActiveSandboxAdapter(options.sandboxAdapter || null);
    if (typeof adapter?.execute !== 'function') {
        throw new SandboxInitializationError('Invalid or missing sandbox adapter.');
    }

    const capabilities = requireSandboxCapabilities(adapter);
    const scrubbedEnv = { ...scrubEnvironmentVariables(options.env || {}), ...validateEphemeralEnv(options.ephemeralEnv || {}) };

    const result = await adapter.execute({
        command,
        args,
        workspace: options.workspace,
        timeoutMs: options.timeoutMs ?? 60000,
        env: scrubbedEnv,
        ...(options.input !== undefined ? { input: options.input } : {}),
        signal: options.signal,
        capabilities
    });

    return {
        ...result,
        adapterId: adapter.id || capabilities?.adapterId || 'unknown',
        capabilities
    };
}
